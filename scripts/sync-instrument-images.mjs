// Regenerate the UI data and offline attribution page from the reviewed ledger.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const images = JSON.parse(readFileSync(resolve(root, 'public/instruments/credits.json'), 'utf8'));
const escape = value =>
  String(value).replace(
    /[&<>"']/g,
    char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char],
  );
for (const [id, item] of Object.entries(images)) {
  if (
    !/^[a-z]+\.(jpg|jpeg|png|svg|webp)$/.test(item.file) ||
    !existsSync(resolve(root, 'public/instruments', item.file))
  )
    throw new Error(`Missing or invalid image: ${id}`);
  for (const field of ['source', 'licenseUrl'])
    if (!item[field].startsWith('https://')) throw new Error(`Invalid ${field}: ${id}`);
}
// The UI module omits download URLs (kept in the ledger for provenance) and stores repeated notes once.
const notes = [...new Set(Object.values(images).map(item => item.note))];
const uiImages = Object.fromEntries(
  Object.entries(images).map(([id, { download, note, ...item }]) => [id, { ...item, note: notes.indexOf(note) }]),
);
writeFileSync(
  resolve(root, 'src/instrument-images.ts'),
  `// Generated by scripts/sync-instrument-images.mjs. Edit public/instruments/credits.json.
export interface InstrumentImageData {
  file: string; width: number; height: number; name: string;
  kind: 'photo' | 'historical' | 'diagram'; alt: string; caption: string;
  author: string; license: string; licenseUrl: string; source: string;
  sourceTitle: string; note: string;
}
const notes: string[] = ${JSON.stringify(notes, null, 2)};
const raw: Record<string, Omit<InstrumentImageData, 'note'> & { note: number }> = ${JSON.stringify(uiImages)};
export const instrumentImages: Record<string, InstrumentImageData> = Object.fromEntries(Object.entries(raw).map(([id, item]) => [id, { ...item, note: notes[item.note] }]));
`,
);
const labels = { photo: '实物照片', historical: '历史图像', diagram: '外形示意' };
const entries = Object.entries(images)
  .map(
    ([id, item]) =>
      `<article id="${id}"><a class="preview" href="./instruments/${item.file}"><img src="./instruments/${item.file}" alt="${escape(item.alt)}" loading="lazy" width="120" height="90"></a><div><h2>${escape(item.name)} <small>${labels[item.kind]}</small></h2><p>${escape(item.caption)}</p><p>作者 / 提供者：${escape(item.author)}</p><p>原始条目：<a href="${escape(item.source)}" target="_blank" rel="noreferrer">${escape(item.sourceTitle)}</a><br>授权：<a href="${escape(item.licenseUrl)}" target="_blank" rel="noreferrer">${escape(item.license)}</a></p><p class="note">${escape(item.note)}</p></div></article>`,
  )
  .join('\n');
writeFileSync(
  resolve(root, 'public/image-credits.html'),
  `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>图片来源与授权 · 音序</title><style>
*{box-sizing:border-box}body{font:15px/1.8 system-ui,sans-serif;background:#f7f6f0;color:#45513f;margin:0}main{max-width:980px;padding:36px 22px;margin:auto}h1{font-size:28px;font-weight:500}a{color:#3e6a47;overflow-wrap:anywhere}header{margin-bottom:30px}article{display:flex;gap:22px;border-top:1px solid #d9dfcf;padding:24px 0}article>div{min-width:0}article h2{font-size:20px;margin:0}h2 small{font-size:11px;color:#75826b;font-weight:400}article p{margin:8px 0;font-size:13px}.preview{flex:0 0 120px;height:100px;background:#eeeae0;border-radius:7px}img{object-fit:contain;width:120px;height:100px;padding:5px}.note{color:#7b846f}@media(max-width:540px){article{gap:12px}.preview{flex-basis:80px}img{width:80px}h1{font-size:24px}}
</style></head><body><main><header><a href="./#/courses">← 返回乐器课程</a><h1>图片来源与授权</h1><p>图鉴的 ${Object.keys(images).length} 个配图条目包含 ${Object.values(images).filter(item => item.kind === 'photo').length} 张实物照片、${Object.values(images).filter(item => item.kind === 'historical').length} 幅历史图像及 ${Object.values(images).filter(item => item.kind === 'diagram').length} 幅原创结构示意。每幅图展示代表形制，不涵盖同名乐器的全部地域变体。</p><p>图片已包含在网站和离线包中。第三方图片各自遵循下列授权；本项目代码的 MIT 许可证不替代图片授权。图源页面和许可证链接需联网打开。</p><p>示意图用于认识主要部件，不能作为尺寸、指法、弦数或制器依据。结构参考见课程资料及 <a href="https://github.com/xxzzh/yinyue/blob/main/docs/instrument-images.md">配图说明</a>。</p></header>${entries}</main></body></html>\n`,
);
console.log(`Synced ${Object.keys(images).length} image records and offline attribution page.`);
