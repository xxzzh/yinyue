// Writes src/lesson-index.ts: titles, intros and durations of every course and lesson for the first screen.
// Run with `npm run index` after editing lessons; `npm run build` runs it too, and a test fails when the
// committed index no longer matches the lesson content.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { courses } from '../src/data.ts';
import { traditionalInstrument } from '../src/traditional-catalog.ts';
import { toCourseMeta } from '../src/course-meta.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const index = courses.map(course => toCourseMeta(course, traditionalInstrument(course.id)?.tradition));
writeFileSync(
  resolve(root, 'src/lesson-index.ts'),
  `// Generated by scripts/build-lesson-index.mjs from the lesson modules. Do not edit; run \`npm run index\`.
import type { CourseMeta } from './course-meta';
// JSON.parse keeps start-up parsing fast for a large literal.
export const courseIndex: CourseMeta[] = JSON.parse(${JSON.stringify(JSON.stringify(index))});
`,
);
console.log(
  `Indexed ${index.length} courses and ${index.reduce((sum, course) => sum + course.lessons.length, 0)} lessons.`,
);
