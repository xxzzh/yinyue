import { createServer } from 'node:http';
import { createReadStream, existsSync } from 'node:fs';
import { stat } from 'node:fs/promises';
import { dirname, extname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const directory = dirname(fileURLToPath(import.meta.url));
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.json': 'application/json; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.woff': 'font/woff', '.woff2': 'font/woff2' };

export function createStaticServer(root) {
  root = resolve(root);
  return createServer(async (request, response) => {
    if (!['GET', 'HEAD'].includes(request.method)) { response.writeHead(405, { Allow: 'GET, HEAD' }).end('Method not allowed'); return; }
    let pathname;
    try { pathname = decodeURIComponent(new URL(request.url, 'http://127.0.0.1').pathname); }
    catch { response.writeHead(400).end('Bad request'); return; }
    const path = resolve(root, `.${pathname === '/' ? '/index.html' : pathname}`);
    if (!path.startsWith(root + sep)) { response.writeHead(403).end('Forbidden'); return; }
    try {
      if (!(await stat(path)).isFile()) { response.writeHead(404).end('Not found'); return; }
    } catch { response.writeHead(404).end('Not found'); return; }
    response.writeHead(200, { 'Content-Type': types[extname(path)] || 'application/octet-stream', 'Cache-Control': 'no-cache' });
    if (request.method === 'HEAD') response.end();
    else createReadStream(path).on('error', () => response.destroy()).pipe(response);
  });
}

export async function startLocalServer({ root, port = 4173, attempts = 20 }) {
  if (!Number.isInteger(port) || port < 0 || port > 65535) throw new Error('PORT must be a number between 0 and 65535.');
  if (!existsSync(join(root, 'index.html'))) throw new Error('Website files are missing. Extract the entire ZIP before starting.');
  for (let attempt = 0; attempt < attempts && port + attempt <= 65535; attempt++) {
    const server = createStaticServer(root);
    try {
      await new Promise((ready, failed) => {
        server.once('error', failed);
        server.listen(port + attempt, '127.0.0.1', () => {
          server.removeListener('error', failed);
          ready();
        });
      });
      return { server, url: `http://127.0.0.1:${server.address().port}/` };
    } catch (error) {
      if (error.code !== 'EADDRINUSE') throw error;
    }
  }
  throw new Error('No local port is available. Close previous Yinxu windows and try again.');
}

export function openBrowser(url) {
  // The URL is generated by our server and contains only a loopback host and numeric port.
  const command = process.platform === 'win32' ? 'cmd.exe' : process.platform === 'darwin' ? 'open' : 'xdg-open';
  const args = process.platform === 'win32' ? ['/d', '/s', '/c', `start "" "${url}"`] : [url];
  const child = spawn(command, args, { windowsHide: true, windowsVerbatimArguments: process.platform === 'win32', stdio: 'ignore' });
  child.on('error', () => console.warn(`Please open this address in your browser: ${url}`));
  child.unref();
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = existsSync(join(directory, 'web', 'index.html')) ? join(directory, 'web') : directory;
  startLocalServer({ root, port: Number(process.env.PORT ?? 4173) }).then(({ url }) => {
    console.log(`\nYinxu Music Academy\nOpen: ${url}\nKeep this window open while learning. Close it or press Ctrl+C to stop.\n`);
    if (process.argv.includes('--open') && process.env.YINXU_NO_BROWSER !== '1') openBrowser(url);
  }).catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
