/** One octave of a mode on D, as a listening sequence. */
const modeScale = (mode: string) =>
  Scale.get(`D ${mode}`)
    .intervals.concat('8P')
    .map((interval, i) => `${Note.transpose('D4', interval)}${i === 7 ? ':2' : ''}`)
    .join(' ');

