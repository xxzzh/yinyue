// Conventions follow the original guzheng lessons: 21 strings tuned to D pentatonic (D2–D6), string 21 is the
// lowest, the right hand plucks right of the bridges and the left hand presses left of them. Exercises are
// original; traditional pieces are described for listening rather than transcribed, because versions differ.
import type { Lesson, QuizItem } from './data.ts';

const q = (question: string, options: string[], answer: number, explanation: string, listen?: string): QuizItem => ({
  question,
  options,
  answer,
  explanation,
  ...(listen ? { listen } : {}),
});
type Spec = Omit<Lesson, 'sections' | 'quiz' | 'more'> & { sections: [string, string][]; questions: QuizItem[] };
const lesson = ({ sections, questions, ...rest }: Spec): Lesson => ({
  ...rest,
  sections: sections.map(([title, body]) => ({ title, body })),
  quiz: questions[0],
  more: questions.slice(1),
});
