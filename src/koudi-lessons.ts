// Koudi line lessons for L0–L2 (docs/curriculum-outline.md, section 5.2). IDs: `koudi-l{stage}-{nn}`.
// Two-hole and five-hole koudi differ in fingering and range, so these lessons teach the shared wind technique
// (embouchure, breath, articulation, ornaments) and send fingering questions to the chart of the learner's own
// instrument. Reference examples play an octave up on a soft sine tone; real koudi pitch depends on the model.
import type { Lesson, QuizItem } from './data.ts';

const q = (question: string, options: string[], answer: number, explanation: string, listen?: string): QuizItem => ({
  question,
  options,
  answer,
  explanation,
  ...(listen ? { listen } : {}),
});
type Spec = Omit<Lesson, 'sections' | 'quiz' | 'more'> & { sections: [string, string][]; questions: QuizItem[] };
const lesson = ({ sections, questions, ...rest }: Spec): Lesson => ({
  ...rest,
  sections: sections.map(([title, body]) => ({ title, body })),
  quiz: questions[0],
  more: questions.slice(1),
});
