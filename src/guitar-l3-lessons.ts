/** A chord shape from music.ts as one tablature token (strings 6 → 1); `^` marks an up-strum. */
const shape = (chord: string, beats: number | string = 1, upStrum = false) =>
  `${upStrum ? '^' : ''}${guitarChords[chord]
    .map((fret, index) => (fret < 0 ? '' : `${6 - index}/${fret}`))
    .filter(Boolean)
    .join('+')}:${beats}`;
/** Down, down-up, (miss)-up, down-up over one bar. */
const folk = (chord: string) =>
  [
    shape(chord),
    shape(chord, 0.5),
    shape(chord, 0.5, true),
    'r:0.5',
    shape(chord, 0.5, true),
    shape(chord, 0.5),
    shape(chord, 0.5, true),
  ].join(' ');
/** A sixteenth-note groove over two beats: down, down-up, (miss)-up, down-up. */
const groove = (chord: string) =>
  [
    shape(chord, 0.5),
    shape(chord, 0.25),
    shape(chord, 0.25, true),
    'r:0.25',
    shape(chord, 0.25, true),
    shape(chord, 0.25),
    shape(chord, 0.25, true),
  ].join(' ');
/** Shuffle boogie on two strings: the fifth on beats 1 and 3, the sixth on 2 and 4, swung. */
const boogie = (bass: number, fifth: string, sixth: string) =>
  [fifth, sixth, fifth, sixth].map(top => `${bass}/0+${top}:2/3 ${bass}/0+${top}:1/3`).join(' ');
const bluesBars: Record<string, string> = {
  A: boogie(5, '4/2', '4/4'),
  D: boogie(4, '3/2', '3/4'),
  E: boogie(6, '5/2', '5/4'),
};
