export const worldAreas = ['全部地域', ...new Set(worldCatalog.map(item => item.area))];
export type WorldTrack = (typeof worldCatalog)[number]['id'];
export function worldInstrument(id: string) {
  return worldCatalog.find(item => item.id === id);
}
export function filterWorld(query = '', family = 'all', area = '全部地域') {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return worldCatalog.filter(
    item =>
      (family === 'all' || item.family === family) &&
      (area === '全部地域' || item.area === area) &&
      words.every(word =>
        `${item.name} ${item.english} ${item.aliases.join(' ')} ${item.area} ${item.tradition}`
          .toLowerCase()
          .includes(word),
      ),
  );
}
