export interface WorldInstrument {
  id: string;
  name: string;
  english: string;
  family: Exclude<CourseFamily, 'foundation'>;
  area: string;
  tradition: string;
  aliases: string[];
  shape: string;
  voice: string;
  step: string;
  contrast: string;
  ref: keyof typeof worldSources;
  art: string;
}

function instrument<const ID extends string>(
  id: ID,
  name: string,
  english: string,
  family: WorldInstrument['family'],
  area: string,
  tradition: string,
  shape: string,
  voice: string,
  step: string,
  contrast: string,
  art: string,
  ref: WorldInstrument['ref'] = 'museum',
  aliases: string[] = [],
): WorldInstrument & { id: ID } {
  return { id, name, english, family, area, tradition, shape, voice, step, contrast, art, ref, aliases };
}

