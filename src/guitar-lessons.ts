const q = (question: string, options: string[], answer: number, explanation: string, listen?: string): QuizItem => ({
  question,
  options,
  answer,
  explanation,
  ...(listen ? { listen } : {}),
});
/** Sounding notes of a chord shape for listening examples; up-strums hit the four highest strings. */
const down = (chord: string, beats = 1) => `${chordVoicing(chord).join('+')}:${beats}`;
const up = (chord: string, beats = 0.5) => `^${chordVoicing(chord).slice(-4).join('+')}:${beats}`;
/** The common folk strum over one 4/4 bar: down, down-up, (miss)-up, down-up. */
const folkStrum = (chord: string) =>
  [down(chord), down(chord, 0.5), up(chord), 'r:0.5', up(chord), down(chord, 0.5), up(chord)].join(' ');
/** A chord shape as one tablature token (strings 6 → 1). */
const tabChord = (chord: string, beats = 1) =>
  `${guitarChords[chord]
    .map((fret, index) => (fret < 0 ? '' : `${6 - index}/${fret}`))
    .filter(Boolean)
    .join('+')}:${beats}`;

