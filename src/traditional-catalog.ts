export function filterTraditional(query = '', family = 'all', area = '全部地域'): TraditionalInstrument[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return traditionalCatalog.filter(item => (family === 'all' || item.family === family) && (area === '全部地域' || item.area === area) && words.every(word =>
    `${item.name} ${item.pinyin} ${item.aliases.join(' ')} ${item.tradition} ${item.area}`.toLowerCase().includes(word)));
}
